def test_agentic_extraction_of_a_long_contract(extract_api, truth):
    """100-page PDF, contents on pages 2-3 with printed page numbers 3 lower than physical ones."""
    name = "provider_agreement_long.pdf"
    job, wall = submit(extract_api, name, truth, approach="agentic", sync=False)
    assert job["status"] == "COMPLETED", job.get("error")
    r = job["result_data"]
    ok, misses = score(r["data"], truth[name]["expected"])
    record("extract_agentic_contract_default", summary(job, wall, ok, len(truth[name]["expected"]), misses))
    toc = r["document"]["toc"]
    assert toc["found"] and toc["toc_pages"] == [2, 3] and toc["page_offset"] == 3
    entry = next(e for e in toc["entries"] if e["title"].upper().startswith("ARTICLE 20"))
    assert entry["page"] == truth[name]["fact_pages"]["termination"]
    assert r["document"]["chunking"]["strategy"] == "section"
    assert r["document"]["retrieval"]["mode"] == "hybrid", r["warnings"]
    assert ok >= len(truth[name]["expected"]) - 1, misses
    assert r["usage"]["total"]["cost_usd"] > 0
    assert job["usage"] == r["usage"] and job["stats"]["usage"] == r["usage"]
    assert set(r["usage"]["by_model"]) >= {"anthropic:claude-sonnet-5-5"}
    assert list(r["data"]) == list(truth[name]["spec"]["properties"])
    assert [f["path"] for f in r["fields"]][:3] == ["health_plan_name", "provider_name", "effective_date"]
    assert job["stats"]["model"] == "anthropic:claude-sonnet-5-5"
    file = extract_api.get(f"/jobs/{job['job_id']}/file")
    assert file.status_code == 200 and file.json() == r["data"]


def test_agentic_extraction_stays_inside_a_small_window(extract_api, truth):
    """The usable window is capped at 16000 tokens: about a sixth of the document. Sessions are compacted."""
    name = "provider_agreement_long.pdf"
    job, wall = submit(extract_api, name, truth, approach="agentic", window=16000)
    r = job["result_data"]
    ok, misses = score(r["data"], truth[name]["expected"])
    record("extract_agentic_contract_16k", summary(job, wall, ok, len(truth[name]["expected"]), misses))
    assert r["engine"]["usable_window"] == 16000
    for s in r["agent"]["sessions"]:
        assert s["compact_at_tokens"] == int(16000 * r["engine"]["context_threshold"])
        assert s["peak_context_tokens"] < 16000  # the conversation never outgrew the window
    assert ok >= len(truth[name]["expected"]) - 2, misses


def test_batch_extraction_of_the_long_contract_with_openai(extract_api, truth):
    name = "provider_agreement_long.pdf"
    job, wall = submit(extract_api, name, truth, approach="batch", model="openai:gpt-6.1-sol", window=40000)
    r = job["result_data"]
    ok, misses = score(r["data"], truth[name]["expected"])
    record("extract_batch_contract_gpt61sol", {**summary(job, wall, ok, len(truth[name]["expected"]), misses),
                                               "parts": r["batch"]["parts"], "part_tokens": r["batch"]["part_tokens"]})
    assert r["batch"]["parts"] >= 3 and r["engine"]["model"] == "gpt-6.1-sol"
    assert ok >= len(truth[name]["expected"]) - 2, misses


@pytest.mark.parametrize("name, approach", [("services_agreement.docx", "agentic"), ("lab_results.csv", "agentic"),
                                            ("intake_form.txt", "batch")])
def test_other_formats(extract_user, truth, name, approach):
    job, wall = submit(extract_user, name, truth, approach=approach)
    r = job["result_data"]
    ok, misses = score(r["data"], truth[name]["expected"])
    record(f"extract_{os.path.splitext(name)[0]}_{approach}", summary(job, wall, ok, len(truth[name]["expected"]), misses))
    assert ok == len(truth[name]["expected"]), misses
    if name.endswith(".csv"):
        assert r["document"]["chunking"]["strategy"] == "tabular"
    if name.endswith(".docx"):
        assert r["document"]["toc"]["source"] == "headings"


def test_text_endpoint(extract_api, truth):
    with open(os.path.join(EXTRACT_DIR, "invoice_inline.txt"), encoding="utf-8") as f:
        text = f.read()
    case = truth["invoice_inline.txt"]
    res = extract_api.post("/extract/text", json={"text": text, "approach": "batch", "spec": case["spec"]})
    assert res.status_code == 200, res.text
    body = res.json()
    assert body["data"] == case["expected"]
    assert body["summary"]["found"] == 4
    # the output keeps the requester's key order (the spec is not stored as JSONB, which re-sorts keys)
    assert list(body["data"]) == ["invoice_number", "total_usd", "invoice_date", "payment_terms_days"]
    record("extract_text_endpoint", {"data": body["data"], "usage": body["usage"], "duration_ms": body["duration_ms"]})


