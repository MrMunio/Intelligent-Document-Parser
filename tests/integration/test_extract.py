def _norm(v):
    if isinstance(v, str):
        return v.strip().lower().rstrip(".")
    if isinstance(v, float) and v == int(v):
        return int(v)
    return v


def _get(data, path):
    for part in path.split("."):
        data = (data or {}).get(part) if isinstance(data, dict) else None
    return data


def score(data: dict, expected: dict) -> tuple[int, list]:
    misses, ok = [], 0
    for path, want in expected.items():
        got = _get(data, path)
        if isinstance(want, list) and want and isinstance(want[0], dict):
            got_set = {json.dumps({k: _norm(x.get(k)) for k in want[0]}, sort_keys=True) for x in (got or []) if isinstance(x, dict)}
            match = {json.dumps({k: _norm(x[k]) for k in x}, sort_keys=True) for x in want} <= got_set
        elif isinstance(want, list):
            match = sorted(map(_norm, want)) == sorted(map(_norm, got or []))
        elif isinstance(want, str) and isinstance(got, str):
            match = _norm(want) in _norm(got) or _norm(got) in _norm(want)
        else:
            match = _norm(got) == _norm(want)
        ok += bool(match)
        if not match:
            misses.append({"path": path, "expected": want, "got": got})
    return ok, misses


def submit(client, name, truth, *, approach, model=None, window=None, sync=True):
    data = {"spec": json.dumps(truth[name]["spec"]), "approach": approach}
    if model:
        data["model"] = model
    if window:
        data["context_window"] = str(window)
    with open(os.path.join(EXTRACT_DIR, name), "rb") as f:
        files = {"file": (name, f.read())}
    started = time.perf_counter()
    if sync:
        res = client.post("/extract/sync", files=files, data=data)
        assert res.status_code == 200, res.text
        job = res.json()
    else:
        res = client.post("/extract/jobs", files=files, data=data)
        assert res.status_code == 202, res.text
        job = client.wait(res.json()["job_id"], timeout=900)
    return job, time.perf_counter() - started


def summary(job, wall, ok, total, misses):
    r = job["result_data"]
    agent = r.get("agent") or {}
    return {"file": job["file_name"], "approach": r["approach"], "engine": f"{r['engine']['provider']}:{r['engine']['model']}",
            "usable_window": r["engine"]["usable_window"], "correct": ok, "total": total, "accuracy": round(ok / total, 4),
            "misses": misses, "job_ms": job["duration_ms"], "wall_s": round(wall, 1), "usage": r["usage"]["total"],
            "sessions": [{k: s[k] for k in ("session", "ended", "turns", "tool_calls", "peak_context_tokens", "compact_at_tokens")}
                         for s in agent.get("sessions", [])],
            "compactions": agent.get("compactions"), "toc": (r["document"].get("toc") or {}).get("source"),
            "toc_pages": (r["document"].get("toc") or {}).get("toc_pages"),
            "page_offset": (r["document"].get("toc") or {}).get("page_offset"),
            "chunking": (r["document"].get("chunking") or {}).get("strategy"),
            "retrieval": (r["document"].get("retrieval") or {}).get("mode"), "warnings": r["warnings"]}


