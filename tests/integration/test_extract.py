def test_options_list_engines_from_the_catalog(extract_user):
    opts = extract_user.get("/extract/options").json()
    keys = {m["key"] for m in opts["models"]}
    assert opts["default_model"] == "anthropic:claude-sonnet-5-5" and opts["default_model"] in keys
    # OpenAI selection is limited to the account's models (catalog "account_models")
    assert {"openai:gpt-6.1-sol", "openai:gpt-6.1-terra", "openai:gpt-6-luna"} <= keys and "openai:gpt-6.2-astra" not in keys
    sonnet = next(m for m in opts["models"] if m["key"] == "anthropic:claude-sonnet-5-5")
    assert sonnet["context_window"] == 1_000_000 and sonnet["default"] and sonnet["recommended_for_agentic"]
    assert 0.3 <= opts["context_threshold"] <= 0.95 and opts["example_spec"]["properties"]
    record("extract_options", {"default": opts["default_model"], "models": sorted(keys),
                               "threshold": opts["context_threshold"], "cap": opts["context_cap_tokens"]})


def test_validate_spec_endpoint(extract_user):
    ok = extract_user.post("/extract/validate-spec", json={"spec": {"properties": {
        "total": {"type": "number", "description": "Invoice total"}}}}).json()
    assert ok["valid"] and ok["field_count"] == 1
    bad = extract_user.post("/extract/validate-spec", json={"spec": {"properties": {
        "total": {"type": "money"}, "items": {"type": "array", "description": "Lines"}}}}).json()
    assert not bad["valid"]
    assert {e["path"] for e in bad["errors"]} == {"$.total", "$.items"}
    text = extract_user.post("/extract/validate-spec", json={"spec": '{"properties": '}).json()
    assert not text["valid"] and "not valid JSON" in text["errors"][0]["message"]


def test_invalid_spec_is_rejected_before_the_upload(extract_user):
    before = extract_user.get("/jobs", params={"job_type": "EXTRACT"}).json()["total"]
    res = extract_user.post("/extract/jobs", files={"file": ("a.txt", b"Total: 12")},
                            data={"spec": json.dumps({"properties": {"total": {"type": "number"}}})})
    assert res.status_code == 422
    detail = res.json()["detail"]
    assert detail["errors"] == [{"path": "$.total", "message": detail["errors"][0]["message"]}]
    assert "description is required" in detail["errors"][0]["message"]
    assert extract_user.get("/jobs", params={"job_type": "EXTRACT"}).json()["total"] == before  # no job created
    assert extract_user.post("/extract/jobs", files={"file": ("a.txt", b"x")}, data={
        "spec": json.dumps({"properties": {"t": {"type": "number", "description": "Total"}}}), "approach": "magic"}).status_code == 400
    assert extract_user.post("/extract/jobs", files={"file": ("a.txt", b"x")}, data={
        "spec": json.dumps({"properties": {"t": {"type": "number", "description": "Total"}}}), "model": "nope:model"}).status_code == 400
    assert extract_user.post("/extract/jobs", files={"file": ("a.zip", b"PK\x03\x04")}, data={
        "spec": json.dumps({"properties": {"t": {"type": "number", "description": "Total"}}})}).status_code == 415


